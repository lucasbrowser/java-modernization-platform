\getenv migrator_password MIGRATION_DB_PASSWORD
\getenv runtime_password RUNTIME_DB_PASSWORD
\getenv bootstrap_password BOOTSTRAP_DB_PASSWORD

CREATE ROLE app_migrator LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT
    PASSWORD :'migrator_password';
CREATE ROLE app_runtime LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT
    PASSWORD :'runtime_password';
CREATE ROLE app_bootstrap LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT
    PASSWORD :'bootstrap_password';

CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA public;
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA public TO app_migrator;
